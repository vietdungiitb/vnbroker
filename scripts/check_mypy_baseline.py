"""Fail CI when `mypy vnbroker --strict` reports NEW errors vs the baseline.

- Baseline: ``artifacts/v3.4-roadmap/mypy-baseline.txt`` (expiry 2026-12-31).
- Comparison is line-number agnostic: ``path :: [code] message``.
- Fixing legacy errors is always allowed (baseline shrinks via --update).
- Usage:
    python scripts/check_mypy_baseline.py          # check (CI)
    python scripts/check_mypy_baseline.py --update # regenerate after fixes
"""

from __future__ import annotations

import re
import subprocess
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BASELINE = ROOT / "artifacts" / "v3.4-roadmap" / "mypy-baseline.txt"

_ERROR_RE = re.compile(r"^(?P<path>.+?):\d+(?::\d+)?: error: (?P<msg>.*)$")


def run_mypy_strict() -> str:
    # --no-incremental: mypy 2.x incremental cache under-reports on the
    # first run after source changes; CI must be deterministic.
    proc = subprocess.run(
        [sys.executable, "-m", "mypy", "vnbroker", "--strict", "--no-incremental"],
        cwd=ROOT,
        capture_output=True,
        text=True,
    )
    return (proc.stdout or "") + (proc.stderr or "")


def normalize(output: str) -> Counter[str]:
    """Collapse `path:line[:col]: error: msg [code]` → `path :: [code] msg`.

    Line numbers are stripped (edits shift them), but multiplicity is kept:
    adding a second identical error in the same file still counts as new.
    """
    items: Counter[str] = Counter()
    for line in output.splitlines():
        match = _ERROR_RE.match(line.strip())
        if not match:
            continue
        path = match.group("path").replace("\\", "/")
        msg = re.sub(r"\s+", " ", match.group("msg")).strip()
        items[f"{path} :: {msg}"] += 1
    return items


def load_baseline() -> Counter[str]:
    if not BASELINE.exists():
        return Counter()
    items: Counter[str] = Counter()
    for line in BASELINE.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if line and not line.startswith("#"):
            items[line] += 1
    return items


def write_baseline(items: Counter[str]) -> None:
    header = (
        "# mypy --strict baseline (ISSUE-00). Expiry: 2026-12-31.\n"
        "# Generated by `python scripts/check_mypy_baseline.py --update`.\n"
        "# Format: <path> :: <message incl. [code]> (line numbers stripped,\n"
        "# duplicates kept — one line per occurrence).\n"
    )
    body = "\n".join(sorted(items.elements()))
    BASELINE.write_text(header + body + "\n", encoding="utf-8")


def main(argv: list[str]) -> int:
    current = normalize(run_mypy_strict())
    if "--update" in argv:
        write_baseline(current)
        print(f"Baseline updated: {sum(current.values())} strict errors recorded.")
        return 0

    baseline = load_baseline()
    if not baseline:
        print(f"Baseline missing: {BASELINE} — run with --update first.")
        return 2

    new_counter = current - baseline  # keeps only positive counts
    fixed = sum((baseline - current).values())
    new_total = sum(new_counter.values())
    if new_total:
        print(f"FAIL: {new_total} NEW mypy --strict errors "
              f"(baseline {sum(baseline.values())}, "
              f"now {sum(current.values())}, fixed {fixed}):")
        shown = 0
        for err in sorted(new_counter.elements()):
            if shown >= 50:
                break
            print(f"  + {err}")
            shown += 1
        if new_total > 50:
            print(f"  ... and {new_total - 50} more")
        return 1

    print(f"OK: no new strict errors "
          f"(baseline {sum(baseline.values())}, "
          f"now {sum(current.values())}, fixed {fixed}).")
    if fixed:
        print("Note: run with --update to shrink the baseline.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
