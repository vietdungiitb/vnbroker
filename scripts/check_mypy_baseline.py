"""Fail CI when `mypy vnbroker --strict` reports NEW errors vs the baseline.

- Baseline: ``artifacts/v3.4-roadmap/mypy-baseline.txt`` (expiry 2026-12-31).
- Comparison is line-number agnostic: ``path :: [code] message``.
- Fixing legacy errors is always allowed (baseline shrinks via --update).
- Usage:
    python scripts/check_mypy_baseline.py          # check (CI)
    python scripts/check_mypy_baseline.py --update # regenerate after fixes
"""

from __future__ import annotations

import re
import subprocess
import sys
from collections import Counter
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BASELINE = ROOT / "artifacts" / "v3.4-roadmap" / "mypy-baseline.txt"

_ERROR_RE = re.compile(r"^(?P<path>.+?):\d+(?::\d+)?: error: (?P<msg>.*)$")


def run_mypy_strict() -> str:
    # --no-incremental: mypy 2.x incremental cache under-reports on the
    # first run after source changes; CI must be deterministic.
    proc = subprocess.run(
        [sys.executable, "-m", "mypy", "vnbroker", "--strict", "--no-incremental"],
        cwd=ROOT,
        capture_output=True,
        text=True,
        # `text=True` ma KHONG khai bao encoding => Python decode theo locale
        # Windows (cp1252). Output mypy chua tieng Viet co dau (0x90…) =>
        # UnicodeDecodeError trong thread reader => stdout/stderr = None.
        # `(proc.stdout or "")` che loi bang RONG string, nen baseline se
        # "xanh" trong khi mypy co the that bai. Silent false-pass.
        encoding="utf-8",
        errors="replace",
    )
    return (proc.stdout or "") + (proc.stderr or "")


def normalize(output: str) -> Counter[str]:
    """Collapse `path:line[:col]: error: msg [code]` → `path :: [code] msg`.

    Line numbers are stripped (edits shift them), but multiplicity is kept:
    adding a second identical error in the same file still counts as new.
    """
    items: Counter[str] = Counter()
    for line in output.splitlines():
        match = _ERROR_RE.match(line.strip())
        if not match:
            continue
        path = match.group("path").replace("\\", "/")
        msg = re.sub(r"\s+", " ", match.group("msg")).strip()
        items[f"{path} :: {msg}"] += 1
    return items


def baseline_is_expired(today: date | None = None) -> bool:
    """Baseline có quá hạn không — đọc ngày trong header baseline.

    Hạn không phải ghi chú trang trí: quá hạn thì gate đỏ, buộc phải thu hẹp
    baseline hoặc xin gia hạn có lý do. Đây là thứ khiến việc reset baseline
    không trở thành "xóa luôn gate".
    """
    if not BASELINE.exists():
        return False
    for line in BASELINE.read_text(encoding="utf-8").splitlines()[:12]:
        match = re.search(r"Expiry:\s*(\d{4}-\d{2}-\d{2})", line)
        if match:
            try:
                expiry = date.fromisoformat(match.group(1))
            except ValueError:
                return False
            return (today or date.today()) > expiry
    return False


def load_baseline() -> Counter[str]:
    if not BASELINE.exists():
        return Counter()
    items: Counter[str] = Counter()
    for line in BASELINE.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if line and not line.startswith("#"):
            items[line] += 1
    return items


# Gia hạn 2026-11-24 theo yêu cầu chốt phiên Owner: baseline cũ hết hạn
# 2026-11-01 dù docstring script ghi 2026-12-31. Lần regenerate này chỉ ghi nhận
# tập lỗi strict hiện tại (tool drift mypy/pandas); slice CafeF reference
# không thêm lỗi strict mới (xem docs/handoffs/HANDOFF_2026-11-24_CAFEF_REFERENCE.md).
BASELINE_EXPIRY = "2026-12-31"


def write_baseline(items: Counter[str]) -> None:
    header = (
        f"# mypy --strict baseline. Expiry: {BASELINE_EXPIRY}.\n"
        "# Generated by `python scripts/check_mypy_baseline.py --update`.\n"
        "# Format: <path> :: <message incl. [code]> (line numbers stripped,\n"
        "# duplicates kept — one line per occurrence).\n"
        "#\n"
        f"# Reset ngày 2026-10-02 theo quyết định GĐ4 (phương án 2): baseline cũ\n"
        "# ghi 556 dòng nhưng thực tế có 1266 lỗi strict — baseline đã lệch ngay\n"
        "# từ đầu nên gate luôn đỏ và không bảo vệ được gì. Reset về trạng thái\n"
        "# thật để CI chạy được, hạn 30 ngày để bắt buộc giảm lỗi.\n"
        "#\n"
        "# Ưu tiên giảm dần — phân bố lúc reset (top):\n"
        "#   common/data.py 142 · broker/tcbs/account.py 66\n"
        "#   explorer/vci/company.py 56 · brokerage/tcbs/client.py 36\n"
        "#   connector/dnse/trade.py 33 · broker/tcbs/equity.py 33\n"
    )
    body = "\n".join(sorted(items.elements()))
    BASELINE.write_text(header + body + "\n", encoding="utf-8")


def main(argv: list[str]) -> int:
    current = normalize(run_mypy_strict())
    if "--update" in argv:
        write_baseline(current)
        print(f"Baseline updated: {sum(current.values())} strict errors recorded.")
        return 0

    baseline = load_baseline()
    if not baseline:
        print(f"Baseline missing: {BASELINE} — run with --update first.")
        return 2

    expired = baseline_is_expired()
    if expired:
        print(f"FAIL: baseline đã HẾT HẠN ({BASELINE_EXPIRY}).")
        print(f"  Baseline hiện ghi nhận {sum(baseline.values())} lỗi strict.")
        print("  Hãy xử lý lỗi rồi chạy `--update` để thu hẹp, hoặc hỏi owner "
              "gia hạn kèm lý do.")
        return 1

    new_counter = current - baseline  # keeps only positive counts
    fixed = sum((baseline - current).values())
    new_total = sum(new_counter.values())
    if new_total:
        print(f"FAIL: {new_total} NEW mypy --strict errors "
              f"(baseline {sum(baseline.values())}, "
              f"now {sum(current.values())}, fixed {fixed}):")
        shown = 0
        for err in sorted(new_counter.elements()):
            if shown >= 50:
                break
            print(f"  + {err}")
            shown += 1
        if new_total > 50:
            print(f"  ... and {new_total - 50} more")
        return 1

    print(f"OK: no new strict errors "
          f"(baseline {sum(baseline.values())}, "
          f"now {sum(current.values())}, fixed {fixed}).")
    if fixed:
        print("Note: run with --update to shrink the baseline.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
